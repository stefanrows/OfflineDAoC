-- The artifact scrolls, on the two binders.
--
-- An earlier pass reported complete sets for four artifacts out of
-- fifty-seven. That was wrong: it searched for items with "scroll" in the
-- name, and most artifact scroll sets are not called scrolls. They are
-- letters, journals, diaries, pages, tablets, pieces, volumes and parchments.
-- Searching for the shape they share, "N of 3", finds them all.
--
